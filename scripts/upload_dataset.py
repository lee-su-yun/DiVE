#!/usr/bin/env python3
"""Pack the collected scene data one scene at a time and upload it to the Hub.

Only the files Isaac Sim wrote are archived; everything `preprocessing/` derives
from them (per-view occupancy, ray casting, visibility targets) is left out and
regenerated by the user, and so are the RGB-D frames, which no training stage
reads.

The loop compresses one scene, uploads it, deletes the archive and records the
scene in a state file, so it uses almost no disk and resumes after an
interruption.

    python scripts/upload_dataset.py --repo leesuyun/DiVE-data \
        --low /path/to/beliefmap_low_occlusion_ycb_v3 \
        --high /path/to/beliefmap_high_occlusion_ycb_v3 \
        --test_set /path/to/low_occlusion_test_v1
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

# Written by preprocessing/, regenerated in ~80 s per scene on 32 cores.
DERIVED = {
    "pose.npy", "pre_ray_casting.npy", "post_ray_casting.npy",
    "push_visibility_all.npy", "push_visibility_all_marginal.npy",
    "pre_ray_casting_all_view.npy", "grasp_visibility_all_marginal.npy",
    "grasp_visibility_all_marginal_nomask.npy", "grasp_gains.npz",
    "grasp_gains_nomask.npz", "swept_stack.npz",
}
# Raw, but no training or preprocessing step reads them, and they barely compress.
RGBD = {"rgbd.npz", "pre_rgbd.npz", "semantic.npz", "pre_semantic.npz"}
# Unpacked per-view copies of pre_occ.npz / occ.npz.
SKIP_DIRS = {"pre_occ", "post_occ"}



def scene_files(scene_dir: Path):
    out = []
    for root, dirs, files in os.walk(scene_dir):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            if f in DERIVED or f in RGBD:
                continue
            out.append(os.path.relpath(os.path.join(root, f), scene_dir.parent))
    return sorted(out)


def run(cmd, **kw):
    return subprocess.run(cmd, shell=True, check=True, capture_output=True, text=True, **kw)


HF_CLI = "huggingface-cli"


def upload(repo, local, path_in_repo, token_env, retries=6):
    """Upload one file, retrying transient Hub failures with a growing backoff."""
    for attempt in range(1, retries + 1):
        try:
            run(f'{HF_CLI} upload {repo} "{local}" "{path_in_repo}" --repo-type dataset '
                f'--commit-message "Add {path_in_repo}"', env={**os.environ, **token_env})
            return
        except subprocess.CalledProcessError as e:
            tail = (e.stderr or "").strip().splitlines()[-3:]
            print(f"  ! upload failed ({attempt}/{retries}) {path_in_repo}: "
                  f"{' | '.join(tail)}", flush=True)
            if attempt == retries:
                raise
            time.sleep(min(30 * attempt, 180))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--state", default=str(Path(__file__).with_name("upload_state.json")))
    ap.add_argument("--level", type=int, default=12, help="zstd level")
    ap.add_argument("--stage", default=None, help="scratch dir for one archive at a time")
    ap.add_argument("--low", help="low-occlusion data root")
    ap.add_argument("--high", help="high-occlusion data root")
    ap.add_argument("--test_set", help="held-out test set directory")
    ap.add_argument("--limit", type=int, default=0, help="stop after N scenes (0 = all)")
    ap.add_argument("--hf-cli", default="huggingface-cli")
    args = ap.parse_args()
    global HF_CLI
    HF_CLI = args.hf_cli

    state_path = Path(args.state)
    state = json.loads(state_path.read_text()) if state_path.exists() else {"done": []}
    done = set(state["done"])
    stage = Path(args.stage or tempfile.mkdtemp(prefix="dive_upload_"))
    stage.mkdir(parents=True, exist_ok=True)
    env = {}

    # test set + per-split logs first: small, and they validate the whole path
    SPLITS = {k: v for k, v in (("low", args.low), ("high", args.high)) if v}
    TEST_SET = args.test_set
    if not SPLITS and not TEST_SET:
        ap.error("give at least one of --low, --high, --test_set")

    if TEST_SET and "test" not in done:
        t0 = time.time()
        arc = stage / "low_occlusion_test_v1.tar.zst"
        run(f'tar -cf - -C "{Path(TEST_SET).parent}" "{Path(TEST_SET).name}" '
            f'| zstd -q -{args.level} -T0 -f -o "{arc}"')
        upload(args.repo, arc, "test/low_occlusion_test_v1.tar.zst", env)
        size = arc.stat().st_size
        arc.unlink()
        done.add("test")
        state["done"] = sorted(done)
        state_path.write_text(json.dumps(state))
        print(f"[test] {size/1e6:.0f}MB in {time.time()-t0:.0f}s", flush=True)

    for split in SPLITS:
        root = Path(SPLITS[split])
        for log in ("fallen_log.txt", "tipped_log.txt"):
            key = f"{split}/{log}"
            if (root / log).exists() and key not in done:
                upload(args.repo, root / log, f"scenes/{split}/{log}", env)
                done.add(key)
        scenes = sorted(d for d in os.listdir(root) if d.isdigit() and (root / d).is_dir())
        n_todo = sum(1 for s in scenes if f"{split}/{s}" not in done)
        print(f"[{split}] {len(scenes)} scenes, {n_todo} to go", flush=True)

        uploaded = 0
        for i, sc in enumerate(scenes):
            key = f"{split}/{sc}"
            if key in done:
                continue
            t0 = time.time()
            files = scene_files(root / sc)
            listing = stage / "files.txt"
            listing.write_text("\n".join(files))
            arc = stage / f"{sc}.tar.zst"
            run(f'tar -cf - -C "{root}" -T "{listing}" | zstd -q -{args.level} -T0 -f -o "{arc}"')
            t_pack = time.time() - t0
            size = arc.stat().st_size
            t1 = time.time()
            upload(args.repo, arc, f"scenes/{split}/{sc}.tar.zst", env)
            t_up = time.time() - t1
            arc.unlink()
            done.add(key)
            state["done"] = sorted(done)
            state_path.write_text(json.dumps(state))
            uploaded += 1
            print(f"[{split} {i+1}/{len(scenes)}] {sc}  {len(files)} files  "
                  f"{size/1e6:.0f}MB  pack {t_pack:.0f}s  up {t_up:.0f}s  "
                  f"({size/1e6/max(t_up,1e-6):.1f} MB/s)", flush=True)
            if args.limit and uploaded >= args.limit:
                print(f"[{split}] stopping after {uploaded} scenes (--limit)", flush=True)
                return
    print("all done", flush=True)


if __name__ == "__main__":
    sys.exit(main())
